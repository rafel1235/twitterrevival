CREATE TABLE beta_cohorts (
 slug TEXT PRIMARY KEY CHECK(slug ~ '^[a-z0-9][a-z0-9-]{0,63}$'),
 kind TEXT NOT NULL CHECK(kind IN ('pilot','test')),
 capacity INTEGER NOT NULL CHECK(capacity BETWEEN 1 AND 1000),
 enrollment_open BOOLEAN NOT NULL DEFAULT true,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(kind<>'pilot' OR capacity BETWEEN 30 AND 50)
);
INSERT INTO beta_cohorts(slug,kind,capacity) VALUES('pilot','pilot',50);
CREATE TABLE beta_invites (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
 cohort_slug TEXT NOT NULL REFERENCES beta_cohorts(slug),
 email CITEXT NOT NULL CHECK(length(email::text) BETWEEN 3 AND 254),
 token_hash BYTEA NOT NULL UNIQUE CHECK(octet_length(token_hash)=32),
 issuer_id UUID REFERENCES users(id) ON DELETE SET NULL,
 expires_at TIMESTAMPTZ NOT NULL,
 used_at TIMESTAMPTZ, used_by UUID REFERENCES users(id) ON DELETE SET NULL,
 revoked_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(expires_at>created_at),CHECK(used_at IS NULL OR used_at>=created_at),
 CHECK(revoked_at IS NULL OR revoked_at>=created_at)
);
CREATE INDEX beta_invites_available_idx ON beta_invites(cohort_slug,expires_at) WHERE used_at IS NULL AND revoked_at IS NULL;
CREATE INDEX beta_invites_cursor_idx ON beta_invites(cohort_slug,created_at DESC,id DESC);
CREATE TABLE beta_invite_events (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
 invite_id UUID NOT NULL REFERENCES beta_invites(id) ON DELETE CASCADE,
 actor_id UUID REFERENCES users(id) ON DELETE SET NULL,
 action TEXT NOT NULL CHECK(action IN ('issued','revoked','used')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE beta_members (
 user_id UUID PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 cohort_slug TEXT NOT NULL REFERENCES beta_cohorts(slug),
 joined_at TIMESTAMPTZ NOT NULL DEFAULT now(), last_seen_at TIMESTAMPTZ,
 first_follow_at TIMESTAMPTZ, first_post_at TIMESTAMPTZ, first_interaction_at TIMESTAMPTZ,
 returned_d7_at TIMESTAMPTZ
);
CREATE INDEX beta_members_cohort_idx ON beta_members(cohort_slug,joined_at);
CREATE FUNCTION beta_milestone() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF TG_TABLE_NAME='follows' THEN
  UPDATE beta_members SET first_follow_at=now() WHERE user_id=NEW.follower_id AND first_follow_at IS NULL;
 ELSIF TG_TABLE_NAME='posts' THEN
  UPDATE beta_members SET first_post_at=COALESCE(first_post_at,now()),
    first_interaction_at=CASE WHEN NEW.reply_to_id IS NOT NULL OR NEW.quote_of_id IS NOT NULL THEN COALESCE(first_interaction_at,now()) ELSE first_interaction_at END
    WHERE user_id=NEW.author_id AND (first_post_at IS NULL OR first_interaction_at IS NULL);
 ELSE
  UPDATE beta_members SET first_interaction_at=now() WHERE user_id=NEW.user_id AND first_interaction_at IS NULL;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER beta_follow AFTER INSERT ON follows FOR EACH ROW EXECUTE FUNCTION beta_milestone();
CREATE TRIGGER beta_post AFTER INSERT ON posts FOR EACH ROW EXECUTE FUNCTION beta_milestone();
CREATE TRIGGER beta_like AFTER INSERT ON likes FOR EACH ROW EXECUTE FUNCTION beta_milestone();
CREATE TRIGGER beta_repost AFTER INSERT ON reposts FOR EACH ROW EXECUTE FUNCTION beta_milestone();

-- Durable intent only: link tokens are freshly generated by the worker and
-- remain hashed in auth_tokens. No reusable plaintext token in the job table.
CREATE TABLE mail_jobs (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
 user_id UUID REFERENCES users(id) ON DELETE CASCADE,
 email TEXT NOT NULL DEFAULT '',
 purpose TEXT NOT NULL CHECK(purpose IN ('email_verification','password_reset')),
 attempts INTEGER NOT NULL DEFAULT 0 CHECK(attempts BETWEEN 0 AND 5),
 available_at TIMESTAMPTZ NOT NULL DEFAULT now(), leased_until TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK((purpose='email_verification' AND user_id IS NOT NULL AND email='') OR
       (purpose='password_reset' AND user_id IS NULL AND length(email) BETWEEN 3 AND 254))
);
CREATE UNIQUE INDEX mail_jobs_verification_idx ON mail_jobs(user_id,purpose) WHERE user_id IS NOT NULL;
CREATE UNIQUE INDEX mail_jobs_reset_idx ON mail_jobs(email,purpose) WHERE user_id IS NULL;
CREATE INDEX mail_jobs_ready_idx ON mail_jobs(available_at) WHERE attempts<5;
